CREATE ROLE lapnet_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD :'migrator_password';
CREATE ROLE lapnet_runtime LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD :'runtime_password';
CREATE DATABASE lapnet_dev OWNER lapnet_migrator;
REVOKE ALL ON DATABASE lapnet_dev FROM PUBLIC;
GRANT CONNECT ON DATABASE lapnet_dev TO lapnet_runtime;
\connect lapnet_dev
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO lapnet_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE lapnet_migrator IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO lapnet_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE lapnet_migrator IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO lapnet_runtime;
